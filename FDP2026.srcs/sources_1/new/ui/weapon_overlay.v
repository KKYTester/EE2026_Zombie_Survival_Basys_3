            3: gun_row=112'b0000000000010010001000100010001000100010001000100011000100000000000000000000000000000000000000000000000000000000;
            4: gun_row=112'b0000000000010010001100110011001100110011001100110100000100000000000000000000000000000000000000000000000000000000;
            5: gun_row=112'b0000000000010011001100110011001100110011001100110011010000010000000000000000000000000000000000000000000000000000;
            6: gun_row=112'b0000000000010011001100110001000100010001001100110011010000010000000000000000000000000000000000000000000000000000;
            7: gun_row=112'b0000000000010011001100110001010001000001001100110011010000010000000000000000000000000000000000000000000000000000;
