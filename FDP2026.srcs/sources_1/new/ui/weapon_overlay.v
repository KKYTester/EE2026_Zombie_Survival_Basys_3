            10: gun_row=112'b0000000000010100010001000100010001000100010001000100000100000000000000000000000000000000000000000000000000000000;
            11: gun_row=112'b0000000101010101000100010011001100110011001100010001010100010000000000000000000000000000000000000000000000000000;
            12: gun_row=112'b0001010101010101010100010011001100110011001100010101010101010001000000000000000000000000000000000000000000000000;
            13: gun_row=112'b0001010101010101010101010001010001000100000101010101010101010101000100000000000000000000000000000000000000000000;
            14: gun_row=112'b0001011001010101010101010101000100010001010101010101010101010101010100010000000000000000000000000000000000000000;
            15: gun_row=112'b0000000101100101010101010101010101010101010101010101010101010101010101010001000000000000000000000000000000000000;
            16: gun_row=112'b0000000000010110011001010101010101010101010101010101010101010101010101010110000100000000000000000000000000000000;
            17: gun_row=112'b0000000000000001000101100110010101010101010101010101010101010101010101100110011101110001000000000000000000000000;
            18: gun_row=112'b0000000000000000000000010001011001100110010101010101010101010110011001110111011101110111000100000000000000000000;
            19: gun_row=112'b0000000000000000000000000000000101110111011001100110011001100110011101110111011101110111011100010000000000000000;
            20: gun_row=112'b0000000000000000000000000000000000010111011101110111011101110111011101110111011101110111011101110001000000000000;
            21: gun_row=112'b0000000000000000000000000000000000000001011101110111011101110111011101110111011101110111011101110111000100000000;
            22: gun_row=112'b0000000000000000000000000000000000000000000101110111011101110111011101110111011101110111011101110111011100010000;
            23: gun_row=112'b0000000000000000000000000000000000000000000000010111011101110111011101110111011101110111011101110111011101110001;
            default: gun_row=0;
        endcase
    end
    wire [3:0] gun_index = gun_row[111-sx*4 -: 4];
    wire [5:0] fy0 = gy0 - FH;
    wire [6:0] fx = px - FX;
    wire [5:0] fy = py - fy0;
    wire in_flash = show && flash && px>=FX && px<FX+FW && py>=fy0 && fy<FH;
    reg [39:0] flash_row;
    always @* begin
        case(fy)
            0: flash_row=40'b0000000000000000100010000000000000000000;
            1: flash_row=40'b0000000010000000100010000000100000000000;
            2: flash_row=40'b0000000000001000100110011000000000000000;
            3: flash_row=40'b0000100010001001101010101001100010000000;
            4: flash_row=40'b0000000010001001101010101001100000000000;
            5: flash_row=40'b0000000000001000100110011000000000000000;
            default: flash_row=0;
        endcase
    end
    wire [3:0] flash_index = flash_row[39-fx*4 -: 4];
    function [15:0] colour;
        input [3:0] i;
        case(i)
            1: colour=16'h18A2;   // K
            2: colour=16'hC67A;   // w
            3: colour=16'h6B8F;   // g
            4: colour=16'h39E9;   // d
            5: colour=16'hD4CF;   // S
            6: colour=16'hA349;   // s
            7: colour=16'h3A87;   // c
            8: colour=16'hFF27;   // Y
            9: colour=16'hFC62;   // O
            10: colour=16'hFFFF;   // W
            default: colour=16'h0000;
        endcase
    endfunction
    always @* begin
        pixel_out=pixel_in;
        if(in_gun && gun_index!=0) pixel_out=colour(gun_index);
        if(in_flash && flash_index!=0) pixel_out=colour(flash_index);
    end
endmodule
